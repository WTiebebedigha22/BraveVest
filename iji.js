#!/usr/bin/env node
/**
 * BraveVest — Convert Groups, Referral, Documents, Goals to PortalLayout
 *
 * These 4 pages currently use PageShell (no sidebar, wrong theme).
 * Rewrites them to use PortalLayout with design tokens + fade-in animations.
 *
 * Usage:
 *   node iji.js
 *   node iji.js --dry-run
 */

const fs = require('fs');
const path = require('path');

const ROOT = process.cwd();
const SRC = path.join(ROOT, 'bravevest-web', 'src');
const INVESTOR = path.join(SRC, 'pages', 'investor');
const DRY = process.argv.includes('--dry-run');
const STAMP = new Date().toISOString().replace(/[:.]/g, '-');
const BACKUP = path.join(ROOT, '.bravevest-backup', STAMP);

const C = { g: '\x1b[32m', y: '\x1b[33m', b: '\x1b[36m', x: '\x1b[0m' };
const ok = (m) => console.log(`${C.g}✅${C.x} ${m}`);
const warn = (m) => console.log(`${C.y}⚠️ ${C.x} ${m}`);
const info = (m) => console.log(`${C.b}ℹ️ ${C.x} ${m}`);
const head = (m) => console.log(`\n${C.b}━━ ${m} ━━${C.x}`);

function backup(file) {
  if (!fs.existsSync(file)) return;
  const rel = path.relative(ROOT, file);
  const dest = path.join(BACKUP, rel);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(file, dest);
}
function write(file, lines) {
  const rel = path.relative(SRC, file);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  if (DRY) return info(`[dry-run] would write ${rel}`);
  backup(file);
  fs.writeFileSync(file, lines.join('\n'));
  ok(`wrote ${rel}`);
}

if (!fs.existsSync(SRC)) {
  console.error('❌ bravevest-web/src not found. Run from repo root.');
  process.exit(1);
}

console.log('\n🎯 BraveVest — Convert 4 pages to PortalLayout\n');
if (DRY) console.log('   mode: DRY RUN\n');

